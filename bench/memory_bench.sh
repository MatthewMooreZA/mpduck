#!/usr/bin/env bash
# Compare peak memory (and wall time) of read_mpfile against an equivalent read_csv.
#
# The read_csv baseline reads a byte-identical copy of the mpfile data, without the footer and under a
# non-mpfile extension (so MPFileSystem does not intercept it), skipping the metadata/VARIABLE_TYPES rows
# with skip=3 and treating the '!' row as the header.
#
# Usage: bench/memory_bench.sh [rows] [duckdb-binary]
#   rows            number of data rows to generate (default 1000000)
#   duckdb-binary   DuckDB shell with mpduck loaded (default ./build/release/duckdb)
# Environment: BENCH_DIR (default /tmp/mpduck-bench), RUNS (default 3), THREADS (default "1 2"), MEM_LIMIT (default 2GB)
set -euo pipefail

ROWS="${1:-1000000}"
DUCKDB="${2:-./build/release/duckdb}"
BENCH_DIR="${BENCH_DIR:-/tmp/mpduck-bench}"
RUNS="${RUNS:-3}"
THREADS="${THREADS:-1 2}"
MEM_LIMIT="${MEM_LIMIT:-2GB}"
LOW="nice -n 19 ionice -c3"
SKIP=3 # 2 KV_METADATA rows + VARIABLE_TYPES; the '!' row is then the CSV header

mkdir -p "$BENCH_DIR"
SRC="$BENCH_DIR/rows_${ROWS}.rpt"    # generated by COPY: metadata + VARIABLE_TYPES + header + data, no footer
CSV="$BENCH_DIR/rows_${ROWS}.txt"    # identical bytes, non-mpfile extension
MPF="$BENCH_DIR/rows_${ROWS}_footer.rpt" # same data plus a footer, as real mpfiles have

if [[ ! -f "$SRC" ]]; then
	echo "Generating $ROWS rows in $SRC ..."
	$LOW "$DUCKDB" -c "
SET threads=2; SET memory_limit='$MEM_LIMIT';
COPY (
  SELECT 'P' || lpad(i::VARCHAR, 9, '0') AS POLICY,
         'PROD' || (i % 50)::VARCHAR AS PRODUCT,
         (18 + i % 60)::SMALLINT AS AGE,
         (5 + i % 30)::INTEGER AS TERM,
         (i % 1000) * 1000.5 AS SA,
         (i % 777) * 12.25 AS PREM,
         (i % 97) / 100.0 AS RATE,
         (i % 41) * 0.5 AS DUR
  FROM range($ROWS) t(i)
) TO '$SRC' (FORMAT mpfile, KV_METADATA {run: 'bench', version: '1'});"
fi
[[ -f "$CSV" ]] || cp "$SRC" "$CSV"
if [[ ! -f "$MPF" ]]; then
	cp "$SRC" "$MPF"
	printf 'This is a footer line\r\nMore footer, with, commas\r\n' >>"$MPF"
fi
echo "data: $(du -h "$SRC" | cut -f1)  head: $(head -c 200 "$SRC" | tr '\r\n' '  ' | cut -c1-120)"

COLS="POLICY VARCHAR, PRODUCT VARCHAR, AGE SMALLINT, TERM INTEGER, SA DOUBLE, PREM DOUBLE, RATE DOUBLE, DUR DOUBLE"
AGG="count(*) AS n, max(length(POLICY)) AS l, sum(AGE) AS a, sum(TERM) AS t, sum(SA) AS sa, sum(PREM) AS p, sum(RATE) AS r, sum(DUR) AS d"

# name | query. All aggregate so the measurement is scanner memory, not result materialisation.
declare -A Q
Q[mpfile_agg]="SELECT $AGG FROM read_mpfile('$MPF')"
Q[csv_skip_dtypes_agg]="SELECT $AGG FROM (SELECT * EXCLUDE (\"!\") FROM read_csv('$CSV', skip=$SKIP, header=true, dtypes={'!': 'VARCHAR', POLICY: 'VARCHAR', PRODUCT: 'VARCHAR', AGE: 'SMALLINT', TERM: 'INTEGER', SA: 'DOUBLE', PREM: 'DOUBLE', RATE: 'DOUBLE', DUR: 'DOUBLE'}))"
Q[csv_explicit_agg]="SELECT $AGG FROM read_csv('$CSV', skip=$SKIP, header=true, auto_detect=false, delim=',', quote='\"', escape='\"', new_line='\\r\\n', columns={'!': 'VARCHAR', $(echo "$COLS" | sed -E "s/([A-Z]+) ([A-Z]+)/'\1': '\2'/g")})"
Q[mpfile_count]="SELECT count(*) FROM read_mpfile('$MPF')"
Q[csv_skip_dtypes_count]="SELECT count(*) FROM read_csv('$CSV', skip=$SKIP, header=true, dtypes={'!': 'VARCHAR', POLICY: 'VARCHAR', PRODUCT: 'VARCHAR', AGE: 'SMALLINT', TERM: 'INTEGER', SA: 'DOUBLE', PREM: 'DOUBLE', RATE: 'DOUBLE', DUR: 'DOUBLE'})"

ORDER=(mpfile_agg csv_skip_dtypes_agg csv_explicit_agg mpfile_count csv_skip_dtypes_count)

# Idle baseline: the shell with the extension loaded, running a trivial query.
base_kb=$( { /usr/bin/time -f '%M' "$DUCKDB" -csv -noheader -c "SELECT 1" >/dev/null; } 2>&1 | tail -1)
echo "idle shell peak RSS: $((base_kb / 1024)) MB (subtract for scanner-only memory)"

printf '%-24s %7s %22s %8s  %s\n' query threads "rss_MB min/med/max" wall_s result
for th in $THREADS; do
	for name in "${ORDER[@]}"; do
		rss=()
		best_t=999999
		result=""
		for _ in $(seq "$RUNS"); do
			out=$(mktemp)
			tm=$(mktemp)
			$LOW /usr/bin/time -f '%M %e' -o "$tm" "$DUCKDB" -csv -noheader -c "SET threads=$th; SET memory_limit='$MEM_LIMIT'; ${Q[$name]};" >"$out" 2>"$out.err" || {
				echo "FAILED: $name"; cat "$out.err"; exit 1
			}
			read -r kb secs <"$tm"
			result=$(tail -1 "$out" | cut -c1-40)
			rss+=("$((kb / 1024))")
			awk -v a="$secs" -v b="$best_t" 'BEGIN{exit !(a<b)}' && best_t=$secs
			rm -f "$out" "$out.err" "$tm"
		done
		sorted=($(printf '%s\n' "${rss[@]}" | sort -n))
		printf '%-24s %7s %22s %8s  %s\n' "$name" "$th" \
			"${sorted[0]}/${sorted[$((${#sorted[@]} / 2))]}/${sorted[-1]}" "$best_t" "$result"
	done
done
